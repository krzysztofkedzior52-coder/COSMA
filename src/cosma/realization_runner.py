"""Realizations in parallel worker processes.

Realizations do not depend on each other and every seed is derived from (base seed, n, attempt, stage), so the result of a realization
is the same whatever the number of workers or the order they finish in. Worker processes are started with the 'spawn' method on every
platform (the same behaviour on Windows, and no forked numba or Qt state); each receives the project, the grid and the plan once, builds
its own manager, and makes the realizations given to it. A worker writes the cache file itself when a cache folder is set. What comes
back is the light record (status, attempt, check) - the arrays stay in the cache or are regenerated by export from the seeds.

Cost: every worker holds its own copy of the model, the simulation arrays and a numba-compiled kernel (loaded from numba's on-disk cache
after the first run), so memory grows with the number of workers; ``memory_estimate`` is a rough figure to choose it by. Speed-up is
limited by the number of physical cores and by memory bandwidth; the user chooses the number of workers."""

from __future__ import annotations

import multiprocessing as mp
import os
import time
from concurrent.futures import FIRST_COMPLETED, ProcessPoolExecutor, wait

from .progress import Cancelled
from .realizations import RealizationError, RealizationManager

_W: dict = {}

# Calibrated 2026-11-12 with benchmarks/bench_realizations.py (flat synthetic model, SIS facies + 2 properties + permeability,
# 12 neighbours, 3 multigrid levels, Linux, resident memory): one process peaked at 0.43 GB for 1M cells and 1.05 GB for 4M cells;
# parent + 2 workers peaked at 1.33 GB (1M) and 2.85 GB (4M). The constants below are those figures rounded up by about 10%.
BASE_BYTES = 250e6              # per worker: interpreter, numpy, numba and the compiled kernels
BYTES_PER_CELL = 220            # per worker and cell: model copy, simulation arrays, results of one realization
PARENT_BASE_BYTES = 250e6       # this process
PARENT_BYTES_PER_CELL = 200     # this process: the model and what the grid build left behind


def memory_estimate(cells: int, workers: int) -> float:
    """Rough bytes of RAM for this process plus ``workers`` worker processes on a model of ``cells`` cells. Measured on one
    synthetic case (see above); more properties, a longer search template or faulted geometry will need more. Not a guarantee."""
    return PARENT_BASE_BYTES + PARENT_BYTES_PER_CELL * cells + workers * (BASE_BYTES + BYTES_PER_CELL * cells)


def cpu_count() -> int:
    try:
        return len(os.sched_getaffinity(0))
    except AttributeError:
        return os.cpu_count() or 1


def physical_memory() -> float | None:
    """Installed RAM in bytes, or None when the system will not say."""
    try:
        return float(os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES"))
    except (AttributeError, ValueError, OSError):
        pass
    try:
        import ctypes

        class MS(ctypes.Structure):
            _fields_ = [("l", ctypes.c_ulong), ("load", ctypes.c_ulong), ("total", ctypes.c_ulonglong), ("avail", ctypes.c_ulonglong),
                        ("pt", ctypes.c_ulonglong), ("pa", ctypes.c_ulonglong), ("vt", ctypes.c_ulonglong), ("va", ctypes.c_ulonglong),
                        ("ve", ctypes.c_ulonglong)]
        m = MS()
        m.l = ctypes.sizeof(MS)
        ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(m))
        return float(m.total)
    except Exception:
        return None


def check_memory(cells: int, workers: int):
    """-> (message, ok). ok is False when the estimate exceeds the installed RAM; the message is always the estimate."""
    need, have = memory_estimate(cells, workers), physical_memory()
    gb = lambda b: f"{b / 1e9:.1f} GB"          # noqa: E731
    msg = f"{workers} worker(s) on {cells:,} cells: roughly {gb(need)} of memory including this window (an estimate from one benchmark)"
    if have is None:
        return msg + "; the installed memory could not be read", True
    msg += f", this computer has {gb(have)}"
    if need > have:
        return msg + ". That does not fit: choose fewer workers.", False
    if need > 0.7 * have:
        msg += ". This is above 70% of the installed memory; other programs may be slowed down"
    return msg, True


def _init(project, model, plan, regression, cache_dir, frac, stop):
    _W["mgr"] = RealizationManager(project, model, plan, regression=regression, cache_dir=cache_dir)
    _W["frac"], _W["stop"] = frac, stop


def _work(n: int):
    mgr, frac, stop = _W["mgr"], _W["frac"], _W["stop"]

    def cb(label, f):
        if stop.is_set():
            raise Cancelled()
        frac[n] = f
    t0 = time.monotonic()
    try:
        r = mgr.realize(n, cb, keep_arrays=False)
    except Cancelled:
        return n, None, 0.0
    frac[n] = 1.0
    return n, r, time.monotonic() - t0


def run_parallel(manager: RealizationManager, numbers, workers: int, tracker=None, cancelled=lambda: False, on_result=None,
                 poll: float = 0.2):
    """Makes realizations ``numbers`` (all of them not yet in the cache; cached ones are read in this process) with ``workers``
    processes. ``tracker`` (progress.Tracker) is updated; ``cancelled()`` is polled and stops the run (finished realizations are
    kept). -> ({n: light record}, stopped: bool). A worker error stops everything and is raised as RealizationError."""
    if not (isinstance(workers, int) and workers >= 1):
        raise RealizationError("the number of workers must be a whole number >= 1")
    results: dict = {}
    todo = []
    for n in numbers:
        if manager.has_cache(n):
            results[n] = manager.realize(n, keep_arrays=False)
            if on_result:
                on_result(results[n])
        else:
            todo.append(n)
    if not todo:
        return results, False
    ctx = mp.get_context("spawn")
    count = manager.plan.count
    frac = ctx.Array("d", count, lock=False)
    stop = ctx.Event()
    stopped = False
    ex = ProcessPoolExecutor(max_workers=min(workers, len(todo)), mp_context=ctx, initializer=_init,
                             initargs=(manager.project, manager.model, manager.plan, manager.regression, manager.cache_dir, frac, stop))
    try:
        futs = {ex.submit(_work, n): n for n in todo}
        pending = set(futs)
        while pending:
            done, pending = wait(pending, timeout=poll, return_when=FIRST_COMPLETED)
            for f in done:
                if f.cancelled():
                    continue
                n, r, _ = f.result()                    # a worker exception is raised here
                if r is None:
                    continue
                results[n] = r
                if tracker is not None:
                    tracker.item_done()
                if on_result:
                    on_result(r)
            if tracker is not None:
                tracker.update_running(sum(frac[futs[f]] for f in pending if frac[futs[f]] < 1.0))
            if cancelled() and not stopped:
                stopped = True
                stop.set()
                for f in pending:
                    f.cancel()
        return results, stopped
    except BaseException:
        stop.set()
        raise
    finally:
        ex.shutdown(wait=True, cancel_futures=True)
